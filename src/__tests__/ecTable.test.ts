// Re-derives the per-block data-codeword sequence the way the library does.
function deriveBlockSeq(numBlocks: number, totalData: number): number[] {
  const shortLen = Math.floor(totalData / numBlocks);
  const numShort = numBlocks - (totalData % numBlocks);
  const seq: number[] = [];
  for (let b = 0; b < numBlocks; b++)
    seq.push(b < numShort ? shortLen : shortLen + 1);
  return seq;
}

describe('EC table compaction reproduces ISO Table 9', () => {
  it('capacity + block split match the original table for all 160 entries', () => {
    for (let v = 1; v <= 40; v++) {
      for (let l = 0; l < 4; l++) {
        const [, groups] = TABLE9[(v - 1) * 4 + l];
        const origSeq: number[] = [];
        for (const [n, d] of groups)
          for (let k = 0; k < n; k++) origSeq.push(d);
        const numBlocks = groups.reduce((s, [n]) => s + n, 0);
        const totalData = origSeq.reduce((s, d) => s + d, 0);
        expect(getDataCodewordsCapacity(v, l)).toBe(totalData);
        expect(deriveBlockSeq(numBlocks, totalData)).toEqual(origSeq);
      }
    }
  });

  it('interleaveBlocks length matches capacity + ecc for all 160 entries', () => {
    for (let v = 1; v <= 40; v++) {
      for (let l = 0; l < 4; l++) {
        const [ecPerBlock, groups] = TABLE9[(v - 1) * 4 + l];
        const numBlocks = groups.reduce((s, [n]) => s + n, 0);
        const capacity = getDataCodewordsCapacity(v, l);
        const out = interleaveBlocks(new Array(capacity).fill(0), v, l);
        expect(out).toHaveLength(capacity + numBlocks * ecPerBlock);
      }
    }
  });
});
